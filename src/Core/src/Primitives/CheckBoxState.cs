namespace Microsoft.Maui
{
	/// <summary>Specifies the complete state of a checkbox.</summary>
	public enum CheckBoxState
	{
		/// <summary>The checkbox is unchecked.</summary>
		Unchecked,
		/// <summary>The checkbox is checked.</summary>
		Checked,
		/// <summary>The checkbox represents a partial or mixed selection.</summary>
		Indeterminate
	}
}
